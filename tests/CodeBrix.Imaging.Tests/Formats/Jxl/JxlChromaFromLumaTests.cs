using System;
using CodeBrix.Imaging.Formats.Jxl.Encoder.VarDct;
using CodeBrix.Imaging.Formats.Jxl.Modular;
using CodeBrix.Imaging.Formats.Jxl.Rendering;
using CodeBrix.Imaging.Formats.Jxl.VarDct;
using CodeBrix.Imaging.Memory;
using Xunit;

namespace CodeBrix.Imaging.Tests.Formats.Jxl;

public class JxlChromaFromLumaTests
{
    [Theory]
    [InlineData(.25f, 0, -1, -29, -29)] [InlineData(.25f, 0, 1, 28, 28)]
    [InlineData(.25f, 1, -1, -29, -29)] [InlineData(.25f, 1, 1, 28, 28)]
    [InlineData(1f, 0, -1, -29, -29)] [InlineData(1f, 0, 1, 28, 28)]
    [InlineData(1f, 1, -1, -29, -29)] [InlineData(1f, 1, 1, 28, 28)]
    [InlineData(4f, 0, -1, -29, -29)] [InlineData(4f, 0, 1, 28, 28)]
    [InlineData(4f, 1, -1, -29, -29)] [InlineData(4f, 1, 1, 28, 28)]
    [InlineData(32f, 0, -1, -29, 0)] [InlineData(32f, 0, 1, 28, 5)]
    [InlineData(32f, 1, -1, -29, 0)] [InlineData(32f, 1, 1, 28, 5)]
    [InlineData(128f, 0, -1, -29, 0)] [InlineData(128f, 0, 1, 28, 0)]
    [InlineData(128f, 1, -1, -29, 0)] [InlineData(128f, 1, 1, 28, 0)]
    public void multiplier_search_matches_native_vectors_across_outlier_thresholds(float amplitude, int basis, int sign, int expectedFast, int expectedRobust)
    {
        // Generated by FindBestMultiplier in pinned libjxl
        // ef67fde2ec16d52e644c5a0969230b9a85e3eb31, N_SSE2, with 1e-9
        // regularization. Inputs are original deterministic CodeBrix samples.
        // Larger amplitudes cross the robust fit's 100-unit outlier threshold.
        Span<float> luma = stackalloc float[64], chroma = stackalloc float[64];
        for (int i = 0; i < luma.Length; i++)
        {
            luma[i] = ((i * 37) % 131 - 65) * amplitude;
            chroma[i] = (basis + sign * .375f) * luma[i] + ((i * 19) % 17 - 8) * amplitude;
        }

        Assert.Equal(expectedFast, JxlChromaFromLuma.Find(luma, chroma, basis, true));
        Assert.Equal(expectedRobust, JxlChromaFromLuma.Find(luma, chroma, basis, false));
    }

    [Theory]
    [InlineData(5, -1)] [InlineData(7, -1)] [InlineData(5, 18)] [InlineData(7, 18)]
    [InlineData(5, 10)] [InlineData(7, 11)] [InlineData(5, 13)] [InlineData(7, 17)]
    public void correlation_search_reduces_known_chroma_residuals_and_handles_constant_edge_tiles(int effort, int transformIndex)
    {
        var allocator = Configuration.Default.MemoryAllocator;
        using JxlFloatFrame xyb = new(allocator, 3, 3); using JxlModularWorkspace workspace = new(allocator, 10000);
        JxlModularPlane xMap = workspace.Allocate(2, 2), bMap = workspace.Allocate(2, 2);
        for (int c = 0; c < 3; c++) { xyb.Planes[c] = allocator.Allocate2D<float>(65, 65); }
        for (int y = 0; y < 65; y++)
        {
            for (int x = 0; x < 65; x++)
            {
                float luma = .3f + .1f * MathF.Sin(x * .7f + y * .3f);
                xyb.Planes[0].DangerousGetRowSpan(y)[x] = .3f * luma + .02f;
                xyb.Planes[1].DangerousGetRowSpan(y)[x] = luma;
                xyb.Planes[2].DangerousGetRowSpan(y)[x] = 1.5f * luma - .1f;
            }
        }
        using Buffer2D<JxlVarBlock> blocks = transformIndex < 0 ? null : allocator.Allocate2D<JxlVarBlock>(9, 9, AllocationOptions.Clean);
        if (blocks != null)
        {
            for (int y = 0; y < 9; y++)
            {
                for (int x = 0; x < 9; x++)
                {
                    if (blocks.DangerousGetRowSpan(y)[x].Multiplier != 0) { continue; }
                    JxlTransformType type = x < 8 && y < 8 ? (JxlTransformType)transformIndex : JxlTransformType.Dct8;
                    (int w, int h) = type.Blocks();
                    for (int dy = 0; dy < h; dy++) { blocks.DangerousGetRowSpan(y + dy).Slice(x, w).Fill(new(type, -1)); }
                    blocks.DangerousGetRowSpan(y)[x] = new(type, 1 + ((x + y) % 3));
                }
            }
        }
        JxlChromaFromLuma.Compute(xyb, xMap, bMap, effort, TestContext.Current.CancellationToken, blocks, 512);
        // The bounded robust Newton fit discards large residuals and need not
        // converge to the least-squares slope. Both searches must improve the
        // known signal over default X=0, B=Y correlation.
        Assert.True(Math.Abs(.3f - xMap.Get(0, 0) / 84f) < .3f);
        Assert.True(Math.Abs(.5f - bMap.Get(0, 0) / 84f) < .5f);
        if (effort == 5) { Assert.InRange(xMap.Get(0, 0), 18, 27); Assert.InRange(bMap.Get(0, 0), 34, 44); }
        Assert.Equal(0, xMap.Get(1, 1)); Assert.Equal(0, bMap.Get(1, 1));
    }
}
